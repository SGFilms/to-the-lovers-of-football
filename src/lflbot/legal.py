"""Оферта и политика конфиденциальности.

Это черновики: перед запуском с боевым магазином их должен проверить юрист или сам
исполнитель. Тексты в HTML, который понимает Telegram (<b>, <i>, <a>), поэтому одни и те же
строки показываются и в боте, и на страницах /offer и /privacy. В Telegram сообщение не
длиннее 4096 символов: тест следит, чтобы тексты в него помещались."""

from dataclasses import dataclass
from decimal import Decimal
from html import escape

NOT_SET = "не указано"


@dataclass(frozen=True)
class Seller:
    name: str
    inn: str
    email: str


OFFER = """\
📄 <b>Публичная оферта</b>

<b>1. Стороны.</b> Исполнитель: {name}, плательщик налога на профессиональный доход \
(самозанятый), ИНН {inn}. Заказчик: любое лицо, оплатившее подписку в Telegram-боте \
исполнителя (далее — бот).

<b>2. Предмет.</b> Исполнитель открывает заказчику доступ к функциям бота: поиск команды \
и показ ближайших матчей любительской футбольной лиги ЛФЛ (дата, время, соперник, \
стадион). Данные берутся с открытого сайта page.lfl.ru. Исполнитель не связан с ЛФЛ и \
не отвечает за изменения расписания и ошибки на этом сайте.

<b>3. Стоимость и оплата.</b> Подписка стоит {price} ₽ за {days} дней. Оплата через \
платёжный сервис ЮKassa. Автопродления нет: каждое продление оплачивается отдельно. \
Чек выдаётся в соответствии с законом о налоге на профессиональный доход.

<b>4. Акцепт.</b> Оплата подписки означает полное согласие с этой офертой.

<b>5. Срок доступа.</b> Доступ открывается сразу после поступления оплаты и действует \
{days} дней. Продление до окончания срока добавляет {days} дней к текущей дате \
окончания.

<b>6. Возврат.</b> Если бот не работал по вине исполнителя, заказчик может написать \
через кнопку «Написать отзыв» или на email исполнителя. Исполнитель вернёт деньги за \
подписку в течение 10 рабочих дней тем же способом, которым она оплачена. После \
возврата доступ за этот платёж отключается.

<b>7. Ответственность.</b> Сервис предоставляется «как есть». Ответственность \
исполнителя ограничена суммой, уплаченной заказчиком за текущую подписку.

<b>8. Контакты.</b> Email: {email}. Споры решаются переговорами, а при недостижении \
согласия — по законодательству Российской Федерации.
"""

PRIVACY = """\
🔒 <b>Политика конфиденциальности</b>

<b>Что хранит бот.</b> Числовой Telegram ID, дату начала и окончания подписки, дату \
использования бесплатного примера, последнюю команду, расписание которой вы смотрели, и \
сведения о платежах: номер платежа в ЮKassa, сумму, статус и даты.

<b>Чего бот не хранит.</b> Имя, ник, телефон, email и данные банковской карты. Карту \
вы вводите на странице ЮKassa, бот её не видит.

<b>Отзывы.</b> Отзыв пересылается исполнителю в Telegram и в базе бота не сохраняется.

<b>Зачем.</b> Чтобы знать, до какой даты у вас подписка, засчитать каждую оплату ровно \
один раз, напомнить об окончании подписки и показать кнопку с вашей командой.

<b>Кому передаётся.</b> Никому. Платёж обрабатывает ЮKassa по своим правилам.

<b>Сколько хранится.</b> Пока вы пользуетесь ботом. Данные о платежах хранятся столько, \
сколько требует налоговое законодательство.

<b>Удаление.</b> Напишите через кнопку «Написать отзыв» или на {email}, и данные будут \
удалены, кроме тех, что нужно хранить по закону.

Оператор: {name}, ИНН {inn}.
"""


def _seller_fields(seller: Seller) -> dict[str, str]:
    return {
        "name": escape(seller.name or NOT_SET),
        "inn": escape(seller.inn or NOT_SET),
        "email": escape(seller.email or NOT_SET),
    }


def format_amount(price: Decimal) -> str:
    """1 → «1», 1.5 → «1,50»."""
    if price == price.to_integral_value():
        return str(int(price))
    return f"{price:.2f}".replace(".", ",")


def offer_text(seller: Seller, price: Decimal, days: int) -> str:
    return OFFER.format(**_seller_fields(seller), price=format_amount(price), days=days).strip()


def privacy_text(seller: Seller) -> str:
    return PRIVACY.format(**_seller_fields(seller)).strip()
